    [Fact]
    public void PlayerInventoryGrid_ShouldEnforce6x10Footprints_AndActivateFiveElementsHiddenAffixSlots()
    {
        var sink = new RecordingOutboundSink();
        var player = new PlayerZoneState(
            runtimeNpcId: 10001u,
            accountId: Guid.NewGuid(),
            characterId: Guid.NewGuid(),
            leaseEpoch: 1L,
            roleNameUnicode: "Độc Cô Cầu Bại",
            gender: CharacterGender.Male,
            series: ElementSeries.Earth, // Earth generates Metal
            level: 20,
            experience: 0,
            leadExperience: 0,
            mapId: 53,
            currentMpsX: 52000,
            currentMpsY: 101696,
            currentLife: 300,
            maxLife: 300,
            currentMana: 200,
            maxMana: 200,
            currentStamina: 150,
            maxStamina: 150,
            strength: 100,
            dexterity: 100,
            vitality: 100,
            energy: 50,
            lucky: 10,
            unallocatedAttributePoints: 0,
            unallocatedSkillPoints: 0,
            inventoryMoney: 5000,
            repositoryMoney: 0,
            currentFactionId: 255,
            firstFactionId: 255,
            factionJoinCount: 0,
            initialTick: 1L,
            outboundSink: sink);

        // 1. Test 2x3 Weapon in 6x10 EquipRoom collision
        var swordTpl = new ItemTemplate(
            Id: 1001,
            Code: "thanh-cuong-kiem",
            Name: "Thanh Cương Kiếm",
            Genre: ItemGenreKind.Equipment,
            Quality: ItemQualityKind.Normal,
            DetailType: 0, // Melee Weapon -> EquipmentPartKind.Weapon (part 3)
            ParticularType: 1,
            Level: 2,
            ElementSeries: ElementSeries.Metal,
            GridWidthCells: 2,
            GridHeightCells: 3,
            ObjDataId: 4,
            AppearanceResId: 1,
            PriceGold: 500,
            MaxStackCount: 1,
            BaseAttributes:
            [
                new ItemBaseAttributeTemplate(1, "damage_v", 20, 40),
            ],
            Requirements:
            [
                new ItemRequirementTemplate(36, "level", 10),
            ]);

        // Slot 0 (explicit): +50 LifeMax (85)
        // Slot 1 (hidden 1): +20% Lightning Resist (103)
        // Slot 3 (hidden 2): +30% Poison Resist (101)
        // Slot 5 (hidden 3): +40% Fire Resist (102)
        var swordAffixes = new[]
        {
            new ItemMagicAttributeSlot(0, 85, 50, 0, 0, 5),
            new ItemMagicAttributeSlot(1, 103, 20, 0, 0, 5),
            new ItemMagicAttributeSlot(2, 121, 15, 0, 0, 5),
            new ItemMagicAttributeSlot(3, 101, 30, 0, 0, 5),
            new ItemMagicAttributeSlot(4, 166, 40, 0, 0, 5),
            new ItemMagicAttributeSlot(5, 102, 40, 0, 0, 5),
        };

        var swordSlot = new PlayerItemSlot(
            runtimeItemId: 1u,
            domainItemId: Guid.NewGuid(),
            template: swordTpl,
            genre: ItemGenreKind.Equipment,
            detailType: 0,
            particularType: 1,
            level: 2,
            series: ElementSeries.Metal,
            quality: ItemQualityKind.Normal,
            randomSeed: 123u,
            generatorVersion: ItemConsts.GeneratorVersion,
            luck: 10,
            currentDurability: 50,
            maxDurability: 50,
            stackCount: 1,
            containerPlace: ItemContainerPlace.EquipRoom,
            gridX: 0,
            gridY: 0,
            magicAttributes: swordAffixes);

        Assert.True(player.Inventory.TryPlaceItemDirect(swordSlot, ItemContainerPlace.EquipRoom, 0, 0, player));
        // Overlapping (1, 1) in EquipRoom should fail
        Assert.False(player.Inventory.IsEquipRoomRectFree(1, 1, 1, 1));
        Assert.True(player.Inventory.IsEquipRoomRectFree(2, 0, 2, 3));

        // 2. Move sword from EquipRoom (0, 0) to Equip slot Weapon (3, 0)
        // Activating parts for Weapon (part 3) per ms_ActivedEquip: Amulet (part 6) and Body (part 1).
        // Metal is generated by Earth (Thổ sinh Kim).
        Assert.True(player.Inventory.TryMoveOrSwapItem(
            player,
            ItemContainerPlace.EquipRoom,
            0,
            0,
            ItemContainerPlace.Equip,
            (byte)EquipmentPartKind.Weapon,
            0));

        Assert.Equal(50, player.BonusLifeMax);
        Assert.Equal(0, player.LightResistPercent); // Hidden slot 1 not yet active
        Assert.False(swordSlot.ActiveHiddenSlots[0]);

        // 3. Equip Earth Body armor (part 1) -> activates Hidden Slot 1 (+20% Lightning Resist)
        var armorTpl = swordTpl with
        {
            Id = 1002,
            DetailType = 2, // Body
            ElementSeries = ElementSeries.Earth,
        };
        var armorSlot = new PlayerItemSlot(
            runtimeItemId: 2u,
            domainItemId: Guid.NewGuid(),
            template: armorTpl,
            genre: ItemGenreKind.Equipment,
            detailType: 2,
            particularType: 1,
            level: 2,
            series: ElementSeries.Earth,
            quality: ItemQualityKind.Normal,
            randomSeed: 124u,
            generatorVersion: ItemConsts.GeneratorVersion,
            luck: 0,
            currentDurability: 50,
            maxDurability: 50,
            stackCount: 1,
            containerPlace: ItemContainerPlace.Equip,
            gridX: (byte)EquipmentPartKind.Body,
            gridY: 0);

        Assert.True(player.Inventory.TryPlaceItemDirect(armorSlot, ItemContainerPlace.Equip, (byte)EquipmentPartKind.Body, 0, player));
        Assert.True(swordSlot.ActiveHiddenSlots[0]);
        Assert.False(swordSlot.ActiveHiddenSlots[1]);
        Assert.Equal(20, player.LightResistPercent);

        // 4. Equip Earth Amulet (part 6) -> together with Earth Body and Earth Player, activates Hidden Slots 2 and 3!
        var amuletTpl = swordTpl with
        {
            Id = 1003,
            DetailType = 4, // Amulet
            GridWidthCells = 1,
            GridHeightCells = 1,
            ElementSeries = ElementSeries.Earth,
        };
        var amuletSlot = new PlayerItemSlot(
            runtimeItemId: 3u,
            domainItemId: Guid.NewGuid(),
            template: amuletTpl,
            genre: ItemGenreKind.Equipment,
            detailType: 4,
            particularType: 1,
            level: 2,
            series: ElementSeries.Earth,
            quality: ItemQualityKind.Normal,
            randomSeed: 125u,
            generatorVersion: ItemConsts.GeneratorVersion,
            luck: 0,
            currentDurability: 50,
            maxDurability: 50,
            stackCount: 1,
            containerPlace: ItemContainerPlace.Equip,
            gridX: (byte)EquipmentPartKind.Amulet,
            gridY: 0);

        Assert.True(player.Inventory.TryPlaceItemDirect(amuletSlot, ItemContainerPlace.Equip, (byte)EquipmentPartKind.Amulet, 0, player));
        Assert.True(swordSlot.ActiveHiddenSlots[0]);
        Assert.True(swordSlot.ActiveHiddenSlots[1]);
        Assert.True(swordSlot.ActiveHiddenSlots[2]);
        Assert.Equal(20, player.LightResistPercent);
        Assert.Equal(30, player.PoisonResistPercent);
        Assert.Equal(40, player.FireResistPercent);
    }

    [Fact]
    public async Task MapZoneWorker_ShouldEnforceOwnerProtectionAndRaceSafetyOnPickup_TickMedicineRegen_AndExecuteTownPortal()
    {
        IOptions<GameAssetsOptions> opts = Options.Create(new GameAssetsOptions
        {
            ServerRootPath = @"D:\Projects\jx-linux-bin\server1",
            DataDirectory = "data",
            ArtifactsDirectory = "artifacts",
            PreferBinarySnapshots = true,
        });
        var itemCatalog = new ItemTemplateCatalog(opts, NullLogger<ItemTemplateCatalog>.Instance);
        var playerCatalog = new PlayerTemplateCatalog(opts, NullLogger<PlayerTemplateCatalog>.Instance);
        var generator = new ItemGenerator(itemCatalog);

        var mapDesc = new MapDescriptor(
            MapId: 53,
            MapNameUnicode: "Ba Lăng Huyện",
            RawSubPath: "balanghuyen",
            RegionBeginX: 0,
            RegionBeginY: 0,
            RegionWidth: 200,
            RegionHeight: 200,
            AllowTownPortal: true);

        var worker = new MapZoneWorker(
            mapDesc,
            new SpySessionLeaseAppService(),
            new ZoneEngineOptions(),
            TimeProvider.System,
            NullLogger.Instance,
            playerTemplateCatalog: playerCatalog,
            itemTemplateCatalog: itemCatalog,
            itemGenerator: generator);

        var sink1 = new RecordingOutboundSink();
        var sink2 = new RecordingOutboundSink();
        Guid char1Id = Guid.NewGuid();
        Guid char2Id = Guid.NewGuid();

        var starterItems = new List<CharacterItemDto>
        {
            new(
                Id: Guid.NewGuid(),
                Genre: ItemGenreKind.Medicine,
                DetailType: 0,
                ParticularType: 1,
                Level: 1,
                Series: ElementSeries.Metal,
                Quality: ItemQualityKind.Normal,
                RandomSeed: 1001u,
                GeneratorVersion: ItemConsts.GeneratorVersion,
                Luck: 0,
                CurrentDurability: 1,
                MaxDurability: 1,
                StackCount: 3,
                ContainerPlace: ItemContainerPlace.Immediacy,
                GridX: 0,
                GridY: 0,
                MagicAttributes: []),
            new(
                Id: Guid.NewGuid(),
                Genre: ItemGenreKind.TownPortal,
                DetailType: 0,
                ParticularType: 1,
                Level: 1,
                Series: ElementSeries.Metal,
                Quality: ItemQualityKind.Normal,
                RandomSeed: 1002u,
                GeneratorVersion: ItemConsts.GeneratorVersion,
                Luck: 0,
                CurrentDurability: 1,
                MaxDurability: 1,
                StackCount: 1,
                ContainerPlace: ItemContainerPlace.Immediacy,
                GridX: 2,
                GridY: 0,
                MagicAttributes: []),
        };

        var dto1 = new CharacterDto(
            Id: char1Id,
            AccountId: Guid.NewGuid(),
            SlotIndex: 0,
            RoleNameUnicode: "Lệnh Hồ Xung",
            Gender: CharacterGender.Male,
            Series: ElementSeries.Metal,
            Level: 10,
            Experience: 0,
            LeadExperience: 0,
            MapId: 53,
            RevivalMapId: 53,
            RevivalPointId: 19,
            MapMpsX: 52500,
            MapMpsY: 102000,
            CurrentLife: 100,
            MaxLife: 300,
            CurrentMana: 100,
            MaxMana: 200,
            CurrentStamina: 150,
            MaxStamina: 150,
            Strength: 50,
            Dexterity: 50,
            Vitality: 50,
            Energy: 50,
            Lucky: 10,
            UnallocatedAttributePoints: 0,
            UnallocatedSkillPoints: 0,
            InventoryMoney: 500,
            RepositoryMoney: 0,
            CurrentFactionId: 255,
            FirstFactionId: 255,
            FactionJoinCount: 0,
            Skills: [],
            Items: starterItems);

        CharacterDto dto2 = dto1 with
        {
            Id = char2Id,
            AccountId = Guid.NewGuid(),
            RoleNameUnicode = "Nhậm Doanh Doanh",
            Items = [],
        };

        worker.TryEnqueueCommand(new AttachPlayerZoneCommand(dto1, 1L, sink1));
        worker.TryEnqueueCommand(new CompletePlayerSyncZoneCommand(char1Id, 1L, 0x1111u, 1u));
        worker.TryEnqueueCommand(new AttachPlayerZoneCommand(dto2, 2L, sink2));
        worker.TryEnqueueCommand(new CompletePlayerSyncZoneCommand(char2Id, 2L, 0x2222u, 1u));
        await worker.StepSingleTickAsync();

        Assert.Equal(2, sink1.ItemSyncs.Count);
        Assert.NotEmpty(sink1.MoneySyncs);

        // 1. Spawn ground item owned by char1 -> char2 cannot pick it up during protection window, char1 can
        GeneratedItemData dropData = generator.GenerateEquipment(0, 1, ElementSeries.Metal, 2, [5, 5, 0, 0, 0, 0], 10);
        GroundObjectSlot groundObj = worker.GroundObjectSystem.SpawnItemGroundObject(
            53,
            null,
            worker.RegionGrid,
            PlayerItemSlot.FromGeneratedItem(9001u, dropData),
            52500,
            102000,
            ownerCharacterId: char1Id,
            currentTick: worker.CurrentFrameTick);

        // Both players attempt to pick up groundObj in the same tick
        worker.TryEnqueueCommand(new PickupGroundObjectZoneCommand(char2Id, 2L, groundObj.ObjId, ItemContainerPlace.EquipRoom, 0, 0));
        worker.TryEnqueueCommand(new PickupGroundObjectZoneCommand(char1Id, 1L, groundObj.ObjId, ItemContainerPlace.EquipRoom, 0, 0));
        await worker.StepSingleTickAsync();

        Assert.Empty(sink2.ItemSyncs);
        Assert.Equal(3, sink1.ItemSyncs.Count);

        // 2. Drink healing potion in Immediacy slot 0 -> decrements stack and ticks gradual HP regen
        uint potionRuntimeId = sink1.ItemSyncs[0].RuntimeItemId;
        worker.TryEnqueueCommand(new UseInventoryItemZoneCommand(char1Id, 1L, potionRuntimeId, ItemContainerPlace.Immediacy, 0, 0));
        for (int t = 0; t < 10; t++)
        {
            await worker.StepSingleTickAsync();
        }

        PlayerZoneState? player1 = null;
        foreach (SpatialRegionSlot slot in worker.RegionGrid.ActiveRegions)
        {
            foreach (PlayerZoneState p in slot.Players)
            {
                if (p.CharacterId == char1Id)
                {
                    player1 = p;
                }
            }
        }

        Assert.NotNull(player1);
        Assert.True(player1!.CurrentLife > 100);

        // 3. Emergency Town Portal (IsEmergencyTownPortal = true) -> consumes scroll (0x60) and teleports to revival point
        player1.FightMode = 1;
        worker.TryEnqueueCommand(new UseInventoryItemZoneCommand(char1Id, 1L, 0, ItemContainerPlace.None, 0, 0, IsEmergencyTownPortal: true));
        await worker.StepSingleTickAsync();

        Assert.NotEmpty(sink1.ItemRemoves);
        Assert.Equal(0, player1.FightMode);
    }

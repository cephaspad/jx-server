using JXServer.Primitives.Characters;

namespace JXServer.Primitives.Combat;

/// <summary>
/// Canonical Five-Elements (<c>Ngũ Hành</c>) generation (<c>Tương Sinh</c> / <c>g_nAccrueSeries</c>)
/// and conquest (<c>Tương Khắc</c> / <c>g_nConquerSeries</c>) rules from <c>KMath.cpp</c>.
/// </summary>
public static class FiveElementsSeriesMatrix
{
    private static readonly ElementSeries[] AccrueTable =
    [
        ElementSeries.Water, // Metal (0) -> Water (2)
        ElementSeries.Fire,  // Wood (1)  -> Fire (3)
        ElementSeries.Wood,  // Water (2) -> Wood (1)
        ElementSeries.Earth, // Fire (3)  -> Earth (4)
        ElementSeries.Metal, // Earth (4) -> Metal (0)
    ];

    private static readonly ElementSeries[] ConquerTable =
    [
        ElementSeries.Wood,  // Metal (0) -> Wood (1)
        ElementSeries.Earth, // Wood (1)  -> Earth (4)
        ElementSeries.Fire,  // Water (2) -> Fire (3)
        ElementSeries.Metal, // Fire (3)  -> Metal (0)
        ElementSeries.Water, // Earth (4) -> Water (2)
    ];

    /// <summary>
    /// Returns <see langword="true"/> if <paramref name="source"/> generates (<c>Tương Sinh</c> / <c>g_IsAccrue</c>) <paramref name="target"/>.
    /// </summary>
    public static bool Generates(ElementSeries source, ElementSeries target)
    {
        int idx = (int)source;
        if ((uint)idx >= (uint)AccrueTable.Length)
        {
            return false;
        }

        return AccrueTable[idx] == target;
    }

    /// <summary>
    /// Returns <see langword="true"/> if <paramref name="source"/> conquers (<c>Tương Khắc</c> / <c>g_IsConquer</c>) <paramref name="target"/>.
    /// </summary>
    public static bool Conquers(ElementSeries source, ElementSeries target)
    {
        int idx = (int)source;
        if ((uint)idx >= (uint)ConquerTable.Length)
        {
            return false;
        }

        return ConquerTable[idx] == target;
    }

    /// <summary>
    /// Gets the element series generated by <paramref name="source"/>.
    /// </summary>
    public static ElementSeries GetGeneratedSeries(ElementSeries source)
    {
        int idx = (int)source;
        return (uint)idx < (uint)AccrueTable.Length ? AccrueTable[idx] : source;
    }

    /// <summary>
    /// Gets the element series conquered by <paramref name="source"/>.
    /// </summary>
    public static ElementSeries GetConqueredSeries(ElementSeries source)
    {
        int idx = (int)source;
        return (uint)idx < (uint)ConquerTable.Length ? ConquerTable[idx] : source;
    }

    /// <summary>
    /// Gets the Five-Elements damage multiplier percentage (<c>120%</c> when <paramref name="attackerSeries"/> conquers <paramref name="defenderSeries"/>,
    /// <c>80%</c> when <paramref name="defenderSeries"/> conquers <paramref name="attackerSeries"/>, or <c>100%</c> otherwise).
    /// </summary>
    public static int GetSeriesDamageMultiplierPercent(ElementSeries attackerSeries, ElementSeries defenderSeries)
    {
        if (Conquers(attackerSeries, defenderSeries))
        {
            return 120;
        }

        if (Conquers(defenderSeries, attackerSeries))
        {
            return 80;
        }

        return 100;
    }
}
